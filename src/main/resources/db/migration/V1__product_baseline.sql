CREATE TABLE chat_messages (
    message_id        UUID        PRIMARY KEY,
    note_id           BIGINT      NOT NULL REFERENCES notes (note_id) ON DELETE CASCADE,
    role              VARCHAR(10) NOT NULL CONSTRAINT ck_chat_messages_role CHECK (role IN ('USER', 'ASSISTANT')),
    status            VARCHAR(20) NOT NULL
        CONSTRAINT ck_chat_messages_status CHECK (status IN ('PENDING', 'STREAMING', 'COMPLETED', 'FAILED', 'CANCELED')),
    -- USER: 의미 입력 원문 {"text": ..., "latex"?: ...}
    user_input        JSONB,
    -- ASSISTANT COMPLETED: canonical response_pages[{response_page_id, presentation, title?, result_blocks}]
    response_pages    JSONB,
    -- ASSISTANT COMPLETED: Source Reference catalog snapshot
    -- [{source_ref_id, asset_id, page_start, page_end, display_label_snapshot}].
    -- Note Asset FK에 묶지 않으므로 asset rename/삭제가 이 snapshot을 바꾸지 않는다.
    source_references JSONB,
    -- 공개 block·source label에서 파생한 plain text (USER는 입력 text). history·검색에 사용.
    plain_text        TEXT,
    content_sha256    VARCHAR(64) CONSTRAINT ck_chat_messages_sha256 CHECK (content_sha256 ~ '^[0-9a-f]{64}$'),
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    completed_at      TIMESTAMPTZ,
    CONSTRAINT uq_chat_messages_note_message_role UNIQUE (note_id, message_id, role),
    CONSTRAINT ck_chat_messages_user CHECK (
        role <> 'USER' OR (
            status = 'COMPLETED'
            AND user_input IS NOT NULL AND jsonb_typeof(user_input) = 'object'
            AND user_input -> 'text' IS NOT NULL
            AND jsonb_typeof(user_input -> 'text') = 'string'
            AND plain_text IS NOT NULL
            AND response_pages IS NULL AND source_references IS NULL AND completed_at IS NULL
        )
    ),
    CONSTRAINT ck_chat_messages_assistant_input CHECK (role <> 'ASSISTANT' OR user_input IS NULL),
    -- STREAMING placeholder는 Activity 진행만 뜻하고 영속 본문이 없다 (Candidate token 저장 금지).
    CONSTRAINT ck_chat_messages_assistant_placeholder CHECK (
        role <> 'ASSISTANT' OR status = 'COMPLETED'
        OR (response_pages IS NULL AND source_references IS NULL AND plain_text IS NULL AND content_sha256 IS NULL)
    ),
    CONSTRAINT ck_chat_messages_assistant_completed CHECK (
        role <> 'ASSISTANT' OR status <> 'COMPLETED' OR (
            response_pages IS NOT NULL AND source_references IS NOT NULL
            AND jsonb_typeof(response_pages) = 'array' AND jsonb_array_length(response_pages) >= 1
            AND jsonb_typeof(source_references) = 'array'
            AND plain_text IS NOT NULL
            AND content_sha256 IS NOT NULL
        )
    ),
    CONSTRAINT ck_chat_messages_assistant_terminal CHECK (
        role <> 'ASSISTANT' OR (status IN ('COMPLETED', 'FAILED', 'CANCELED')) = (completed_at IS NOT NULL)
    )
);

CREATE INDEX idx_chat_messages_note_created ON chat_messages (note_id, created_at, message_id);
CREATE INDEX idx_chat_messages_plain_text_trgm ON chat_messages USING GIN (plain_text gin_trgm_ops);

-- 메시지 식별·소속·입력은 불변이고 terminal 메시지는 더 이상 바뀌지 않는다.
CREATE FUNCTION chat_messages_guard_update() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.message_id <> OLD.message_id OR NEW.note_id <> OLD.note_id OR NEW.role <> OLD.role
        OR NEW.user_input IS DISTINCT FROM OLD.user_input OR NEW.created_at <> OLD.created_at THEN
        RAISE EXCEPTION 'chat_messages identity/input columns are immutable'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    IF OLD.status IN ('COMPLETED', 'FAILED', 'CANCELED') THEN
        RAISE EXCEPTION 'terminal chat message % is immutable', OLD.message_id
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    IF NEW.status <> OLD.status AND NOT (
        (OLD.status = 'PENDING' AND NEW.status IN ('STREAMING', 'COMPLETED', 'FAILED', 'CANCELED'))
        OR (OLD.status = 'STREAMING' AND NEW.status IN ('COMPLETED', 'FAILED', 'CANCELED'))
    ) THEN
        RAISE EXCEPTION 'invalid chat message status transition % -> %', OLD.status, NEW.status
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_chat_messages_guard_update
    BEFORE UPDATE ON chat_messages
    FOR EACH ROW EXECUTE FUNCTION chat_messages_guard_update();

-- Turn Attachment: source user message의 직접 입력. Note Asset·후속 message로 복제하지 않는다.
CREATE TABLE turn_attachments (
    attachment_id              UUID         PRIMARY KEY,
    note_id                    BIGINT       NOT NULL,
    source_message_id          UUID         NOT NULL,
    source_message_role        VARCHAR(10)  NOT NULL DEFAULT 'USER'
        CONSTRAINT ck_turn_attachments_source_role CHECK (source_message_role = 'USER'),
    attachment_index           INTEGER      NOT NULL CONSTRAINT ck_turn_attachments_index CHECK (attachment_index BETWEEN 0 AND 9),
    object_key                 VARCHAR(500) NOT NULL,
    thumbnail_object_key       VARCHAR(500),
    sha256                     VARCHAR(64)  NOT NULL CONSTRAINT ck_turn_attachments_sha256 CHECK (sha256 ~ '^[0-9a-f]{64}$'),
    mime_type                  VARCHAR(100) NOT NULL
        CONSTRAINT ck_turn_attachments_mime CHECK (mime_type IN ('application/pdf', 'image/jpeg', 'image/png', 'image/webp')),
    byte_size                  BIGINT       NOT NULL CONSTRAINT ck_turn_attachments_byte_size CHECK (byte_size > 0),
    page_count                 INTEGER,
    pixel_width                INTEGER,
    pixel_height               INTEGER,
    pixel_count                BIGINT,
    upload_policy_version      VARCHAR(64)  NOT NULL,
    page_understanding_version VARCHAR(64)  NOT NULL,
    image_normalization_version VARCHAR(64) NOT NULL,
    display_label              VARCHAR(200),
    created_at                 TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_turn_attachments_source_message FOREIGN KEY (note_id, source_message_id, source_message_role)
        REFERENCES chat_messages (note_id, message_id, role) ON DELETE CASCADE,
    CONSTRAINT uq_turn_attachments_message_index UNIQUE (source_message_id, attachment_index),
    -- internal-run-v1 _ScopedAsset media 규칙과 동일
    CONSTRAINT ck_turn_attachments_media CHECK (COALESCE(
        CASE WHEN mime_type = 'application/pdf'
            THEN page_count IS NOT NULL AND page_count >= 1
                 AND pixel_width IS NULL AND pixel_height IS NULL AND pixel_count IS NULL
            ELSE page_count IS NULL AND pixel_width IS NOT NULL AND pixel_height IS NOT NULL AND pixel_count IS NOT NULL
                 AND pixel_width >= 1 AND pixel_height >= 1
                 AND pixel_count = pixel_width::BIGINT * pixel_height
        END, FALSE)
    )
);

CREATE INDEX idx_turn_attachments_note ON turn_attachments (note_id);

CREATE TRIGGER trg_turn_attachments_immutable
    BEFORE UPDATE ON turn_attachments
    FOR EACH ROW EXECUTE FUNCTION proovy_reject_update();

