-- content는 불변이며 ACTIVE -> SUPERSEDED 기록만 허용한다. 후속은 이 row를 정정한 row여야 한다.
CREATE FUNCTION verified_solutions_guard_update() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF (to_jsonb(NEW) - 'status' - 'superseded_by_solution_id' - 'superseded_at')
        <> (to_jsonb(OLD) - 'status' - 'superseded_by_solution_id' - 'superseded_at') THEN
        RAISE EXCEPTION 'verified solution % content is immutable', OLD.solution_id
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    IF OLD.status <> 'ACTIVE' OR NEW.status <> 'SUPERSEDED' THEN
        RAISE EXCEPTION 'verified solution % can only move ACTIVE -> SUPERSEDED once', OLD.solution_id
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM verified_solutions s
        WHERE s.solution_id = NEW.superseded_by_solution_id AND s.revises_solution_id = OLD.solution_id
    ) THEN
        RAISE EXCEPTION 'superseded_by must be the solution that revises %', OLD.solution_id
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_verified_solutions_guard_update
    BEFORE UPDATE ON verified_solutions
    FOR EACH ROW EXECUTE FUNCTION verified_solutions_guard_update();

