-- 불변 요청·단조 카운터·상태 전이를 DB에서 강제한다.
CREATE FUNCTION ai_runs_guard_update() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.run_id <> OLD.run_id OR NEW.request_id <> OLD.request_id OR NEW.user_id <> OLD.user_id
        OR NEW.note_id <> OLD.note_id OR NEW.user_message_id <> OLD.user_message_id
        OR NEW.assistant_message_id <> OLD.assistant_message_id
        OR NEW.request_fingerprint <> OLD.request_fingerprint
        OR NEW.request_snapshot <> OLD.request_snapshot OR NEW.policy_snapshot <> OLD.policy_snapshot
        OR NEW.budget_policy_version <> OLD.budget_policy_version
        OR NEW.viewer_snapshot IS DISTINCT FROM OLD.viewer_snapshot
        OR NEW.corpus_snapshot IS DISTINCT FROM OLD.corpus_snapshot
        OR NEW.request_deadline_at <> OLD.request_deadline_at OR NEW.created_at <> OLD.created_at THEN
        RAISE EXCEPTION 'ai_runs request identity/snapshot columns are immutable'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;

    IF OLD.status IN ('COMPLETED', 'FAILED', 'CANCELED') THEN
        -- terminal 뒤에는 Brain runtime cleanup 예약 시각만 기록할 수 있다.
        IF (to_jsonb(NEW) - 'runtime_cleanup_at') <> (to_jsonb(OLD) - 'runtime_cleanup_at') THEN
            RAISE EXCEPTION 'terminal run % is immutable', OLD.run_id
                USING ERRCODE = 'integrity_constraint_violation';
        END IF;
        RETURN NEW;
    END IF;

    IF NEW.attempt < OLD.attempt OR NEW.retry_count < OLD.retry_count OR NEW.last_event_seq < OLD.last_event_seq
        OR NEW.used_llm_calls < OLD.used_llm_calls OR NEW.used_tool_calls < OLD.used_tool_calls
        OR NEW.used_output_tokens < OLD.used_output_tokens OR NEW.used_cost_micros < OLD.used_cost_micros
        OR NEW.used_page_understandings < OLD.used_page_understandings THEN
        RAISE EXCEPTION 'ai_runs attempt/seq/usage counters are monotonic'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;

    -- 새 fence는 새 attempt에서만 발급한다.
    IF NEW.fence_token IS DISTINCT FROM OLD.fence_token AND NEW.attempt = OLD.attempt THEN
        RAISE EXCEPTION 'fence_token can only change with a new attempt'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;

    IF NEW.status <> OLD.status AND NOT (
        (OLD.status = 'PENDING' AND NEW.status IN ('RUNNING', 'CANCELED', 'FAILED'))
        OR (OLD.status = 'RUNNING' AND NEW.status IN ('RETRYING', 'CANCELING', 'COMPLETED', 'FAILED'))
        OR (OLD.status = 'RETRYING' AND NEW.status IN ('RUNNING', 'CANCELING', 'COMPLETED', 'FAILED'))
        OR (OLD.status = 'CANCELING' AND NEW.status = 'CANCELED')
    ) THEN
        RAISE EXCEPTION 'invalid run status transition % -> %', OLD.status, NEW.status
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_ai_runs_guard_update
    BEFORE UPDATE ON ai_runs
    FOR EACH ROW EXECUTE FUNCTION ai_runs_guard_update();

